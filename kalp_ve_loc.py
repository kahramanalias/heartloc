def morans_i(vals, xy_, k=8, perms=999, seed=RS):
    """Satır standartlaştırılmış kNN ağırlıklarıyla Moran's I + permütasyon p."""
    nn = NearestNeighbors(n_neighbors=k + 1).fit(xy_)
    _, idx = nn.kneighbors(xy_)
    idx = idx[:, 1:]                       # kendini dışla
    z = np.asarray(vals, float) - np.mean(vals)
    I = float((z @ z[idx].mean(axis=1)) / (z @ z))   # W satır standart → n/S0 = 1
    rng = np.random.default_rng(seed)
    null = np.empty(perms)
    for i in range(perms):
        zp = rng.permutation(z)
        null[i] = (zp @ zp[idx].mean(axis=1)) / (zp @ zp)
    p = (np.sum(np.abs(null) >= abs(I)) + 1) / (perms + 1)
    return I, p, null


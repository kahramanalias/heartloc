def bir_gecis(model_ad, seed, rejim):
    """Tek model + tohum + rejim: katlama dışı tahminler ve katlama metrikleri."""
    if rejim == "Rastgele":
        spl, grp = KFold(N_BLOCKS, shuffle=True, random_state=seed), None
    elif rejim == "Mekânsal":
        spl, grp = GroupKFold(N_BLOCKS), dengeli_bloklar(xy, seed)
    else:
        spl, grp = GroupKFold(N_BLOCKS), ey_blok
    Xd = xy if model_ad == "Yalnizca_cografya" else X
    oof = np.full(len(yv), np.nan)
    satir = []
    for k, (tr, te) in enumerate(spl.split(Xd, yv, grp)):
        if model_ad == "Yalnizca_cografya":
            mdl = Pipeline([("m", RandomForestRegressor(
                n_estimators=250, min_samples_leaf=3, n_jobs=-1, random_state=seed))])
        else:
            mdl = make_models(seed)[model_ad]
        mdl.fit(Xd[tr], yv[tr])
        p = mdl.predict(Xd[te]); oof[te] = p
        satir.append({"rejim": rejim, "model": model_ad, "tohum": seed, "katlama": k,
                      "R2_katlama": r2_score(yv[te], p),
                      "RMSE": float(np.sqrt(mean_squared_error(yv[te], p))),
                      "MAE": mean_absolute_error(yv[te], p), "n_test": len(te),
                      "blok_ici_var": float(np.var(yv[te], ddof=1))})
    return pd.DataFrame(satir), oof


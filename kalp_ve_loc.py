def dengeli_bloklar(xy_, seed=RS, nx=NX, ny=NY):
    """Eşit SAYIDA ilçe içeren, coğrafi olarak bitişik bloklar.

    KMeans dengesiz kümeler üretiyor (n=2'lik katlamalar R2'yi bozuyor); bunun
    yerine koordinatlar tohuma bağlı bir açıyla döndürülür, önce nx eşit-sayılı
    dikey şeride, her şerit de ny eşit-sayılı hücreye bölünür.
    """
    aci = np.random.default_rng(seed).uniform(0, np.pi)
    R_ = np.array([[np.cos(aci), -np.sin(aci)], [np.sin(aci), np.cos(aci)]])
    P = xy_ @ R_.T
    blok = np.empty(len(P), dtype=int)
    serit = pd.qcut(P[:, 0], nx, labels=False, duplicates="drop")
    for s in np.unique(serit):
        m = serit == s
        blok[m] = s * ny + pd.qcut(P[m, 1], ny, labels=False, duplicates="drop")
    return blok

blocks = dengeli_bloklar(xy, RS)

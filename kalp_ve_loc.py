def fetch(url, dest=None, timeout=120, tries=3, min_bytes=512, sessiz=False):
    """URL'yi indirir, önbelleğe alır, bayt döndürür. Başarısızsa None."""
    if dest:
        p = os.path.join(CACHE, dest)
        if os.path.exists(p) and os.path.getsize(p) > min_bytes:
            return open(p, "rb").read()
    for k in range(tries):
        # önce requests, olmazsa urllib (Colab'da bazı ana bilgisayarlarda
        # requests/urllib3 TLS-proxy sorunu yaşanabiliyor)
        for yol in ("requests", "urllib"):
            try:
                if yol == "requests":
                    r = SESSION.get(url, timeout=timeout)
                    kod, icerik = r.status_code, r.content
                else:
                    import urllib.request
                    rq = urllib.request.Request(
                        url, headers={"User-Agent": "Mozilla/5.0 (research)"})
                    with urllib.request.urlopen(rq, timeout=timeout) as resp:
                        kod, icerik = resp.status, resp.read()
                if kod == 200 and len(icerik) >= min_bytes:
                    if dest:
                        open(os.path.join(CACHE, dest), "wb").write(icerik)
                    return icerik
                if not sessiz:
                    log(f"    [{yol}] HTTP {kod} ({len(icerik)} bayt) — {url[:80]}")
            except Exception as e:
                if not sessiz:
                    log(f"    [{yol}] deneme {k+1}: {type(e).__name__} — {url[:80]}")
        time.sleep(2 + 3 * k)
    return None

def fetch_json_sayfali(base, sayfa=50000, ust_sinir=500000, ek=""):
    """Socrata sayfalama: boş dizi ([]) veri sonu demektir, hata değil."""
    rows, off = [], 0
    while off < ust_sinir:
        b = fetch(f"{base}?$limit={sayfa}&$offset={off}{ek}",
                  dest=None, min_bytes=2, tries=2, sessiz=True)
        if b is None:
            break
        try:
            chunk = json.loads(b)
        except Exception:
            break
        if not chunk:
            break
        rows.extend(chunk)
        off += sayfa
    return rows

def fetch_any(urls, dest=None, **kw):
    for u in urls:
        b = fetch(u, dest=dest, **kw)
        if b is not None:
            log(f"    ✓ {u[:100]}")
            return b, u
    return None, None

